/**
 * Overlay the Hindi content onto the English groups: title + entry text come
 * from ABOUT_GROUPS_HI (matched by id, entries by index), icons stay English
 * (they carry ReactNodes). Falls back to English for any missing id/entry.
 */
export function localizeGroups<G extends LocalizableGroup>(groups: G[]): G[] {
  return groups.map((g) => {
    const hi = ABOUT_GROUPS_HI.find((h) => h.id === g.id);
    if (!hi) return g;
    return {
      ...g,
      title: hi.title,
      entries: g.entries.map((enEntry, i) => {
        const hiEntry = hi.entries[i];
        if (!hiEntry) return enEntry;
        return {
          ...enEntry,
          term: hiEntry.term,
          full: hiEntry.full,
          body: hiEntry.body,
        };
      }),
    };
  });
}

